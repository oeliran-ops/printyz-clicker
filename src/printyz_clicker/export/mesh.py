"""Single tessellation path shared by STL, 3MF, validation and preview."""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

TOLERANCE = 0.01          # mm chordal deviation
ANGULAR_TOLERANCE = 0.15  # rad


@dataclass
class Mesh:
    vertices: np.ndarray   # (n, 3) float64, welded
    faces: np.ndarray      # (m, 3) int64

    @property
    def triangles(self) -> np.ndarray:
        return self.vertices[self.faces]


def tessellate(shape, tol: float = TOLERANCE, ang: float = ANGULAR_TOLERANCE) -> Mesh:
    # OCC caches a triangulation on each face; mixing a cached coarse mesh (e.g. from the
    # preview) with a fresh fine one leaves gaps along shared edges. Always start clean.
    from OCP.BRepTools import BRepTools

    BRepTools.Clean_s(shape.wrapped)
    verts, tris = shape.tessellate(tol, ang)
    v = np.array([(p.X, p.Y, p.Z) for p in verts], dtype=np.float64)
    f = np.array(tris, dtype=np.int64).reshape(-1, 3)
    # weld duplicated face-boundary vertices so the mesh is closed / manifold.
    # Shared edge nodes from adjacent faces differ by float noise, so cluster by distance
    # (grid rounding alone fails when two copies straddle a rounding boundary).
    from scipy.sparse import coo_matrix
    from scipy.sparse.csgraph import connected_components
    from scipy.spatial import cKDTree

    pairs = cKDTree(v).query_pairs(1e-6 * max(1.0, float(np.abs(v).max())), output_type="ndarray")
    n = len(v)
    if len(pairs):
        g = coo_matrix((np.ones(len(pairs)), (pairs[:, 0], pairs[:, 1])), shape=(n, n))
        _, labels = connected_components(g, directed=False)
    else:
        labels = np.arange(n)
    _, first, inverse = np.unique(labels, return_index=True, return_inverse=True)
    v = v[first]
    f = inverse.reshape(-1)[f]
    # drop triangles degenerated by welding
    good = (f[:, 0] != f[:, 1]) & (f[:, 1] != f[:, 2]) & (f[:, 0] != f[:, 2])
    return Mesh(v, f[good])


def mesh_health(mesh: Mesh) -> dict:
    import trimesh

    tm = trimesh.Trimesh(mesh.vertices, mesh.faces, process=False)
    return {
        "watertight": bool(tm.is_watertight),
        "winding_consistent": bool(tm.is_winding_consistent),
        "volume": float(tm.volume),
        "bodies": int(len(tm.split(only_watertight=False))),
        "triangles": int(len(mesh.faces)),
    }


def write_stl(mesh: Mesh, path, name: str = "printyz") -> None:
    tri = mesh.triangles.astype(np.float32)
    n = np.cross(tri[:, 1] - tri[:, 0], tri[:, 2] - tri[:, 0])
    ln = np.linalg.norm(n, axis=1, keepdims=True)
    n = np.divide(n, ln, out=np.zeros_like(n), where=ln > 0)
    rec = np.zeros(len(tri), dtype=[("n", "<f4", 3), ("v", "<f4", (3, 3)), ("a", "<u2")])
    rec["n"], rec["v"] = n, tri
    with open(path, "wb") as fh:
        fh.write(name.encode("ascii", "replace")[:80].ljust(80, b" "))
        fh.write(np.uint32(len(tri)).tobytes())
        fh.write(rec.tobytes())
